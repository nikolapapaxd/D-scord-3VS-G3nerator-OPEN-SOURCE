    data class Parsed(val dial: String, val national: String, val iso: String, val name: String)

    /**
     * Parse full number like +9777283888282 or 9777283888282.
     * Longest dial match wins so +977 is Nepal not +97.
     */
    fun parse(full: String): Parsed? {
        val digits = full.filter { it.isDigit() }
        if (digits.isEmpty()) return null
        for (c in ALL) {
            if (digits.startsWith(c.dial) && digits.length > c.dial.length) {
                return Parsed(c.dial, digits.removePrefix(c.dial), c.iso, c.name)
            }
        }
        if (digits.length >= 8) {
            val try3 = digits.take(3)
            val try2 = digits.take(2)
            val try1 = digits.take(1)
            val hit = ALL.firstOrNull { it.dial == try3 }
                ?: ALL.firstOrNull { it.dial == try2 }
                ?: ALL.firstOrNull { it.dial == try1 }
            if (hit != null) {
                return Parsed(hit.dial, digits.removePrefix(hit.dial), hit.iso, hit.name)
            }
        }
        return null
    }

    fun dialForIso(iso: String): String? =
        ALL.firstOrNull { it.iso.equals(iso, true) }?.dial
